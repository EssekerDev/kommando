function presentation(name: string): Phrase[] {
  const n = learnerName(name)
  return [
    { de: "Guten Tag.", fr: "Bonjour." },
    { de: `Ich heisse ${n}.`, fr: `Je m’appelle ${n}.` },
    { de: "Ich bin 33 Jahre alt.", fr: "J’ai 33 ans." },
    {
      de: "Ich komme aus Frankreich und ich wohne bald in Lausanne.",
      fr: "Je viens de France et j’habite bientôt à Lausanne.",
    },
    {
      de: "Ich bin Polizist von Beruf und ich habe 12 Jahre Erfahrung.",
      fr: "Je suis policier de métier et j’ai 12 ans d’expérience.",
    },
    {
      de: "Ich spreche Französisch, Englisch und ein bisschen Deutsch.",
      fr: "Je parle français, anglais et un peu allemand.",
    },
  ]
}

function email(name: string) {
  const n = learnerName(name)
  return {
    subject: "Kurze Vorstellung",
    body: `Betreff: Kurze Vorstellung

Guten Tag

Ich heisse ${n}. Ich bin Polizist von Beruf und ich habe 12 Jahre Erfahrung. Ich komme aus Frankreich und ich wohne bald in Lausanne.

Ich spreche Französisch und Englisch und ich lerne Deutsch. Können wir bitte einen Termin am Donnerstag um 10 Uhr machen?

Vielen Dank.

Mit freundlichen Grüssen
${n}`,
  }
}

