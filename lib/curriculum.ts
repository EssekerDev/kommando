export function dayById(id: number) {
  return days.find((day) => day.id === id) ?? days[0]
}

export type SpokenLine = {
  id: string
  de: string
  fr: string
  label?: string
}

export function spokenLines(day: Day, name: string): SpokenLine[] {
  const lines: SpokenLine[] = []
  const push = (de: string, fr: string, label?: string) => {
    if (lines.some((line) => line.de === de)) return
    lines.push({ id: `${day.id}-${lines.length}`, de, fr, label })
  }
  for (const line of day.lines(name)) push(line.de, line.fr)
  for (const card of day.cards) {
    for (const example of card.examples ?? []) push(example.de, example.fr)
  }
  for (const item of day.lexicon) push(item.de, item.fr, item.label)
  return lines
}
